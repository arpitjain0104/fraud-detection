"""
Streamlit Fraud Alert Dashboard
--------------------------------
Run this AFTER training (python src/train_isolation_forest.py).

Launch with:
    streamlit run dashboard/app.py
"""

import os
import sys
import pandas as pd
import numpy as np
import streamlit as st
import plotly.express as px

# allow importing from src/
sys.path.append(os.path.join(os.path.dirname(__file__), "..", "src"))

st.set_page_config(
    page_title="Fraud Detection Dashboard",
    page_icon="🚨",
    layout="wide",
)

PRED_PATH = os.path.join("outputs", "predictions.csv")


@st.cache_data
def load_predictions():
    return pd.read_csv(PRED_PATH)


st.title("🚨 Fraud Detection in Financial Transactions")
st.caption("Isolation Forest (anomaly detection) + Random Forest with SMOTE (class-imbalance handling)")

if not os.path.exists(PRED_PATH):
    st.error(
        "outputs/predictions.csv not found.\n\n"
        "Please run the training pipeline first:\n\n"
        "1. python src/generate_data.py\n"
        "2. python src/train_isolation_forest.py\n\n"
        "Then refresh this page."
    )
    st.stop()

df = load_predictions()

# ---------------- Sidebar controls ----------------
st.sidebar.header("⚙️ Filters")
model_choice = st.sidebar.radio(
    "Detection model",
    ["Isolation Forest (unsupervised)", "Random Forest + SMOTE (supervised)"],
)

if model_choice.startswith("Isolation"):
    pred_col, score_col = "iso_forest_pred", "iso_forest_score"
else:
    pred_col, score_col = "rf_smote_pred", "rf_smote_prob"

min_amount = st.sidebar.slider(
    "Minimum transaction amount (₹ / $ equivalent)",
    float(df["Amount"].min()), float(df["Amount"].max()), float(df["Amount"].min())
)

only_alerts = st.sidebar.checkbox("Show only flagged (alert) transactions", value=True)

filtered = df[df["Amount"] >= min_amount]
if only_alerts:
    filtered = filtered[filtered[pred_col] == 1]

# ---------------- KPI row ----------------
col1, col2, col3, col4 = st.columns(4)
col1.metric("Total Transactions", f"{len(df):,}")
col2.metric("Actual Fraud (ground truth)", f"{int(df['Class'].sum()):,}")
col3.metric("Flagged by Model", f"{int(df[pred_col].sum()):,}")
detected = int(((df[pred_col] == 1) & (df["Class"] == 1)).sum())
col4.metric("True Frauds Caught", f"{detected:,}")

st.divider()

# ---------------- Charts ----------------
c1, c2 = st.columns(2)

with c1:
    st.subheader("Alert Score Distribution")
    fig = px.histogram(
        df, x=score_col, color=df["Class"].map({0: "Normal", 1: "Fraud"}),
        nbins=50, barmode="overlay",
        labels={"color": "Actual Label"},
    )
    st.plotly_chart(fig, use_container_width=True)

with c2:
    st.subheader("Transaction Amount vs Alert Score")
    fig2 = px.scatter(
        df.sample(min(2000, len(df)), random_state=1),
        x="Amount", y=score_col,
        color=df.sample(min(2000, len(df)), random_state=1)["Class"].map({0: "Normal", 1: "Fraud"}),
        labels={"color": "Actual Label"},
        opacity=0.6,
    )
    st.plotly_chart(fig2, use_container_width=True)

st.divider()

# ---------------- Alert table ----------------
st.subheader(f"🔔 Flagged Transactions ({len(filtered):,})")
display_cols = ["TransactionID", "Time", "Amount", score_col, pred_col, "Class"]
filtered_sorted = filtered.sort_values(score_col, ascending=False)

st.dataframe(
    filtered_sorted[display_cols].rename(columns={
        pred_col: "Model Alert (1=Fraud)",
        score_col: "Anomaly/Fraud Score",
        "Class": "Actual Label (1=Fraud)",
    }),
    use_container_width=True,
    height=420,
)

csv = filtered_sorted[display_cols].to_csv(index=False).encode("utf-8")
st.download_button("⬇️ Download flagged transactions as CSV", csv, "fraud_alerts.csv", "text/csv")

st.caption(
    "Note: This dashboard runs on a synthetic, anonymized dataset generated by "
    "src/generate_data.py so the project works end-to-end without needing a real "
    "banking dataset. Swap in your own anonymized transaction CSV in the same "
    "format (V1..Vn, Time, Amount, Class) to use real data."
)
